import assert from 'node:assert/strict';
import {stepAssessment,comparisonTone} from '../src/modules/vcoaching/assessment.ts';
const make=()=>({comments:[],versions:[{number:2,fields:{'1':['b'],'4':['b'],'7A':['a'],'7B':['b'],'7C':['c']},revisions:{}}]});
let r=make();
assert.equal(stepAssessment(r,'4').attention,false,'step 04 with content is not automatically a warning');
assert.equal(stepAssessment(r,'4').label,'Chưa đánh giá');
assert.equal(stepAssessment(r,'2').label,'Chưa ánh xạ');
r.comments=[{step:'4',state:'pending',stale:false,rule:'EXPERT',quality:'Cần kiểm chứng'}];
assert.equal(stepAssessment(r,'4').attention,false,'draft is not a published assessment');
r.comments[0].state='approved';
assert.equal(stepAssessment(r,'4').attention,true);
r.comments[0].quality='Đủ rõ';
assert.equal(stepAssessment(r,'4').attention,false);
r.comments[0].quality='Cần kiểm chứng';r.comments[0].stale=true;
assert.equal(stepAssessment(r,'4').attention,false,'stale review is not current');
r.comments[0].stale=false;r.comments[0].version=1;
assert.equal(stepAssessment(r,'4').attention,false,'previous version cannot color current step');
r.comments=[{step:'7B',state:'pending',stale:false,rule:'RULE',problem:'Cần đối chiếu'}];
assert.equal(stepAssessment(r,'7').attention,true,'any unresolved layer marks step 07');
r.comments[0].state='rejected';
assert.equal(stepAssessment(r,'7').attention,false);
assert.equal(comparisonTone('Rõ hơn'),'good');
assert.equal(comparisonTone('Không thay đổi'),'');
assert.equal(comparisonTone('Cần xác minh'),'warn');
assert.equal(comparisonTone('Còn yếu'),'warn');
console.log('13 assessment assertions passed');
